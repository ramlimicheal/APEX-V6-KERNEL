"""Build bench/REPORT.md from the bench/results_<step>.json files.

    python -m bench.report
"""

import json
import re
from pathlib import Path

from bench.specs import EQUIV_SCOPE, SPECS

ROOT = Path(__file__).resolve().parent
STEPS = [
    ("baseline", "baseline: original `verify_function`"),
    ("loops", "(a) + bounded loops"),
    ("calls", "(b) + inlined calls"),
    ("lists", "(c) + int lists / str"),
    ("equiv", "(d) bounded equivalence"),
]
OUTCOMES = ["caught", "missed", "false_alarm", "unsupported"]


def _load():
    return {s: json.loads((ROOT / f"results_{s}.json").read_text())
            for s, _ in STEPS if (ROOT / f"results_{s}.json").exists()}


def _md(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def main():
    res = _load()
    rows = [f"| {label} | " + " | ".join(str(res[s]["summary"][o]) for o in OUTCOMES) + " |"
            for s, label in STEPS if s in res]
    out = ["# APEX on QuixBugs", "",
           "Generated by `python -m bench.report` from `bench/results_*.json`; do not edit by hand.",
           f"QuixBugs commit `{next(iter(res.values()))['quixbugs_commit']}` (MIT licence, see "
           "`bench/quixbugs/LICENSE`). 40 programs, each a buggy and a correct version.", "",
           "## Summary", "",
           "| step | " + " | ".join(OUTCOMES) + " |",
           "|---|" + "---:|" * len(OUTCOMES)]
    out += rows
    out += ["",
            "* **caught**: the buggy version is refuted with a concrete input, a real run of the buggy "
            "QuixBugs file on that input confirms it (wrong output, exception or timeout), and the "
            "correct version is proved up to the bound. Equivalence mode: the two files really "
            "behave differently on the reported input.",
            "* **false_alarm**: the correct version is refuted (equivalence mode: correct vs correct "
            "differs).",
            "* **unsupported**: outside the modeled subset, or the solver gave up; the exact reason is "
            "listed below. Never counted as caught.",
            "* **missed**: everything else, including counterexamples that did not reproduce.",
            "",
            "Spec-mode bound: K = 8 loop iterations, K = 8 nested calls, list/str inputs of length "
            "<= cap (default 8; per-program cap below). Equivalence mode: K = 12, lists of length "
            "0..4. \"Proved\" always means *proved up to that bound*, inside the stated domain.", ""]

    out += ["## Per program", "",
            "| program | " + " | ".join(s for s, _ in STEPS if s in res) + " | cap | domain (spec mode) |",
            "|---|" + "---|" * (len(res) + 2)]
    for name in sorted(SPECS):
        sp = SPECS[name]
        cells = []
        for step, _ in STEPS:
            if step in res:
                r = next(p for p in res[step]["programs"] if p["name"] == name)
                cells.append(r["outcome"])
        dom = sp.domain + (" *(partial spec)*" if sp.partial else "")
        out.append(f"| `{name}` | " + " | ".join(cells) + f" | {sp.cap} | {_md(dom)} |")

    for step, label in STEPS:
        if step not in res:
            continue
        out += ["", f"## Details: {label}", "", "| program | outcome | reason | seconds |", "|---|---|---|---:|"]
        for r in sorted(res[step]["programs"], key=lambda r: r["name"]):
            out.append(f"| `{r['name']}` | {r['outcome']} | {_md(r['reason'])[:300]} | {r.get('seconds', '')} |")

    out += ["", "## Specs", "",
            "One line per program in `bench/specs.py`; `cite` quotes the QuixBugs docstring.", "",
            "| program | args | pre (documented) | post |", "|---|---|---|---|"]
    for name in sorted(SPECS):
        sp = SPECS[name]
        out.append(f"| `{name}` | `{_md(sp.args)}` | `{_md(sp.pre)}` | `{_md(sp.post)}` |")
    out += ["", "## Reproduce", "", "```bash", "pip install -r requirements.txt"]
    out += [f"python -m bench.run --step {s}" for s, _ in STEPS]
    out += ["python -m bench.report", "```", "",
            "No LLM calls and no API keys; pure Z3. Each program runs in its own process with a "
            "wall-clock limit; counterexamples are replayed with `bench/realrun.py` (5 s timeout)."]
    out += ["", f"Equivalence-mode target list ({len(EQUIV_SCOPE)}): " + ", ".join(f"`{n}`" for n in EQUIV_SCOPE) + "."]
    (ROOT / "REPORT.md").write_text("\n".join(out) + "\n")
    readme = ROOT.parent / "README.md"
    text = re.sub(r"(<!-- BENCH-TABLE -->\n).*?(<!-- /BENCH-TABLE -->)",
                  lambda m: m.group(1) + "\n".join(rows) + "\n" + m.group(2), readme.read_text(), flags=re.S)
    readme.write_text(text)
    print("wrote bench/REPORT.md")


if __name__ == "__main__":
    main()
